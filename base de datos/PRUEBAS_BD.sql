-- 16. Conteo de filas por tabla
SELECT 'CRM_USUARIOS' AS TABLA, COUNT(*) AS FILAS FROM CRM_USUARIOS
UNION ALL SELECT 'CRM_CLIENTES', COUNT(*) FROM CRM_CLIENTES
UNION ALL SELECT 'CRM_CONTACTOS', COUNT(*) FROM CRM_CONTACTOS
UNION ALL SELECT 'CRM_FUENTES', COUNT(*) FROM CRM_FUENTES
UNION ALL SELECT 'CRM_LEADS', COUNT(*) FROM CRM_LEADS
UNION ALL SELECT 'CRM_PRODUCTOS', COUNT(*) FROM CRM_PRODUCTOS
UNION ALL SELECT 'CRM_OPORTUNIDADES', COUNT(*) FROM CRM_OPORTUNIDADES
UNION ALL SELECT 'CRM_PROPUESTAS', COUNT(*) FROM CRM_PROPUESTAS
UNION ALL SELECT 'CRM_PROPUESTA_DETALLES', COUNT(*) FROM CRM_PROPUESTA_DETALLES
UNION ALL SELECT 'CRM_ACTIVIDADES', COUNT(*) FROM CRM_ACTIVIDADES
UNION ALL SELECT 'CRM_ETIQUETAS', COUNT(*) FROM CRM_ETIQUETAS
UNION ALL SELECT 'CRM_EQUIPOS', COUNT(*) FROM CRM_EQUIPOS
UNION ALL SELECT 'CRM_CAMPANIAS', COUNT(*) FROM CRM_CAMPANIAS
UNION ALL SELECT 'CRM_MENSAJES', COUNT(*) FROM CRM_MENSAJES;

-- 17. Tablespaces desde DBA (administración)
SELECT TABLESPACE_NAME, STATUS, CONTENTS, EXTENT_MANAGEMENT
FROM DBA_TABLESPACES WHERE TABLESPACE_NAME LIKE 'VIERNES_%';

-- 18. Datafiles físicos
SELECT TABLESPACE_NAME, FILE_NAME, ROUND(BYTES/1024/1024,2) AS TAMANO_MB, AUTOEXTENSIBLE
FROM DBA_DATA_FILES WHERE TABLESPACE_NAME LIKE 'VIERNES_%'
UNION ALL
SELECT TABLESPACE_NAME, FILE_NAME, ROUND(BYTES/1024/1024,2), AUTOEXTENSIBLE
FROM DBA_TEMP_FILES WHERE TABLESPACE_NAME LIKE 'VIERNES_%';