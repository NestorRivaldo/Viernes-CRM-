-- 1. Tablespaces del proyecto
SELECT * FROM VW_VIERNES_TABLESPACES;

-- 2. Datafiles y autoextend
SELECT * FROM VW_VIERNES_DATAFILES;

-- 3. Inventario de objetos
SELECT * FROM VW_VIERNES_OBJETOS;

-- 4. Función: total del pipeline (todas las etapas)
SELECT FN_VIERNES_TOTAL_PIPELINE(NULL) AS PIPELINE_GENERAL FROM dual;

-- 5. Función: pipeline filtrado por etapa
SELECT FN_VIERNES_TOTAL_PIPELINE('NEGOCIACION') AS PIPELINE_NEGOCIACION FROM dual;

-- 6. Función: nombre formateado de usuario
SELECT FN_VIERNES_NOMBRE_USUARIO(1) AS USUARIO_ADMIN FROM dual;

-- 7. Función: valor ponderado por oportunidad (una fila)
SELECT NOMBRE, VALOR, PROBABILIDAD, FN_VIERNES_VALOR_PONDERADO(ID) AS VALOR_PONDERADO
FROM CRM_OPORTUNIDADES;

-- 8. Función: pronóstico total (suma del valor esperado abierto)
SELECT FN_VIERNES_TOTAL_PONDERADO() AS PRONOSTICO_ABIERTO FROM dual;

-- 9. Función: tasa de conversión (% ganadas de las cerradas)
SELECT FN_VIERNES_TASA_CONVERSION() AS TASA_CONVERSION FROM dual;

-- 10. Función: nombre comercial del cliente (empresa o persona)
SELECT ID, NOMBRE, EMPRESA, FN_VIERNES_NOMBRE_CLIENTE(ID) AS CLAVE_COMERCIAL
FROM CRM_CLIENTES ORDER BY ID;

-- 11. Función: pipeline abierto vs. histórico completo
SELECT FN_VIERNES_TOTAL_PIPELINE()          AS ABIERTO,
       FN_VIERNES_TOTAL_PIPELINE(NULL, 'N') AS HISTORICO
FROM dual;

