-- =============================================================================
-- TABLAS: OPORTUNIDADES Y DETALLES/RELACIONES
-- Tablespace Datos/Índices: VIERNES_OPORTUNIDADES, VIERNES_OPOR_CONTACTOS,
--                          VIERNES_OPOR_COLAB, VIERNES_OPOR_PROD
-- =============================================================================

CREATE TABLE CRM_OPORTUNIDADES (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE          VARCHAR2(200 CHAR) NOT NULL,
    CLIENTE_NOMBRE  VARCHAR2(150 CHAR),
    VALOR           NUMBER(14,2),
    PROBABILIDAD    NUMBER(10,0),
    ETAPA           VARCHAR2(20 CHAR) NOT NULL,
    RESPONSABLE     VARCHAR2(100 CHAR),
    FECHA_CIERRE    DATE,
    DESCRIPCION     VARCHAR2(500 CHAR),
    CREADO_EN       TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_OPORTUNIDADES PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_OPORTUNIDADES
) TABLESPACE VIERNES_OPORTUNIDADES;

CREATE TABLE CRM_OPORTUNIDAD_CONTACTOS (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_OPORTUNIDAD  NUMBER(19,0) NOT NULL,
    ID_CONTACTO     NUMBER(19,0) NOT NULL,
    ROL             VARCHAR2(100 CHAR),
    ES_DECISOR      NUMBER(1,0),
    CREADO_EN       TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_OPORTUNIDAD_CONTACTOS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_OPOR_CONTACTOS,
    CONSTRAINT UK_OPORTUNIDAD_CONTACTO UNIQUE (ID_OPORTUNIDAD, ID_CONTACTO) USING INDEX TABLESPACE VIERNES_OPOR_CONTACTOS
) TABLESPACE VIERNES_OPOR_CONTACTOS;

CREATE TABLE CRM_OPORTUNIDAD_COLABORADORES (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_OPORTUNIDAD  NUMBER(19,0) NOT NULL,
    ID_USUARIO      NUMBER(19,0) NOT NULL,
    CREADO_EN       TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_OPORTUNIDAD_COLABORADORES PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_OPOR_COLAB,
    CONSTRAINT UK_OPORTUNIDAD_COLABORADOR UNIQUE (ID_OPORTUNIDAD, ID_USUARIO) USING INDEX TABLESPACE VIERNES_OPOR_COLAB
) TABLESPACE VIERNES_OPOR_COLAB;

CREATE TABLE CRM_OPORTUNIDAD_PRODUCTOS (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_OPORTUNIDAD  NUMBER(19,0) NOT NULL,
    ID_PRODUCTO     NUMBER(19,0) NOT NULL,
    CANTIDAD        NUMBER(10,0),
    CREADO_EN       TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_OPORTUNIDAD_PRODUCTOS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_OPOR_PROD,
    CONSTRAINT UK_OPORTUNIDAD_PRODUCTO UNIQUE (ID_OPORTUNIDAD, ID_PRODUCTO) USING INDEX TABLESPACE VIERNES_OPOR_PROD
) TABLESPACE VIERNES_OPOR_PROD;

CREATE INDEX IX_CRM_OPORTUNIDADES_ETAPA ON CRM_OPORTUNIDADES (ETAPA) TABLESPACE VIERNES_OPORTUNIDADES;
CREATE INDEX IX_CRM_OPORTUNIDADES_CIERRE ON CRM_OPORTUNIDADES (FECHA_CIERRE) TABLESPACE VIERNES_OPORTUNIDADES;
CREATE INDEX IX_CRM_OPORTUNIDAD_CONTACTOS_OP ON CRM_OPORTUNIDAD_CONTACTOS (ID_OPORTUNIDAD) TABLESPACE VIERNES_OPOR_CONTACTOS;
CREATE INDEX IX_CRM_OPORTUNIDAD_CONTACTOS_CT ON CRM_OPORTUNIDAD_CONTACTOS (ID_CONTACTO) TABLESPACE VIERNES_OPOR_CONTACTOS;
CREATE INDEX IX_CRM_OPORTUNIDAD_COLAB_USUARIO ON CRM_OPORTUNIDAD_COLABORADORES (ID_USUARIO) TABLESPACE VIERNES_OPOR_COLAB;
CREATE INDEX IX_CRM_OPORTUNIDAD_PRODUCTOS_PROD ON CRM_OPORTUNIDAD_PRODUCTOS (ID_PRODUCTO) TABLESPACE VIERNES_OPOR_PROD;