-- =============================================================================
-- TABLAS: CRM_EQUIPOS y CRM_EQUIPO_MIEMBROS
-- Tablespace Datos/Índices: VIERNES_EQUIPOS, VIERNES_EQ_MIEMBROS
-- =============================================================================

CREATE TABLE CRM_EQUIPOS (
    ID           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPCION  VARCHAR2(500 CHAR),
    ESTADO       VARCHAR2(20 CHAR) NOT NULL,
    CREADO_EN    TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_EQUIPOS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_EQUIPOS,
    CONSTRAINT UK_CRM_EQUIPOS_NOMBRE UNIQUE (NOMBRE) USING INDEX TABLESPACE VIERNES_EQUIPOS
) TABLESPACE VIERNES_EQUIPOS;

CREATE TABLE CRM_EQUIPO_MIEMBROS (
    ID          NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    EQUIPO_ID   NUMBER(19,0) NOT NULL,
    USUARIO_ID  NUMBER(19,0) NOT NULL,
    CREADO_EN   TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_EQUIPO_MIEMBROS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_EQ_MIEMBROS,
    CONSTRAINT UK_EQUIPO_MIEMBRO UNIQUE (EQUIPO_ID, USUARIO_ID) USING INDEX TABLESPACE VIERNES_EQ_MIEMBROS
) TABLESPACE VIERNES_EQ_MIEMBROS;

CREATE INDEX IX_CRM_EQUIPO_MIEMBROS_USUARIO ON CRM_EQUIPO_MIEMBROS (USUARIO_ID) TABLESPACE VIERNES_EQ_MIEMBROS;