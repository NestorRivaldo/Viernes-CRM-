CREATE TABLE CRM_USUARIOS (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE          VARCHAR2(100 CHAR) NOT NULL,
    APELLIDO        VARCHAR2(100 CHAR) NOT NULL,
    CORREO          VARCHAR2(150 CHAR) NOT NULL,
    PASSWORD_HASH   VARCHAR2(255 CHAR) NOT NULL,
    ROL             VARCHAR2(20 CHAR)  NOT NULL,
    ESTADO          VARCHAR2(20 CHAR)  NOT NULL,
    CREADO_EN       TIMESTAMP(6)       NOT NULL,
    ACTUALIZADO_EN  TIMESTAMP(6),
    CONSTRAINT PK_CRM_USUARIOS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_USUARIOS,
    CONSTRAINT UK_CRM_USUARIOS_CORREO UNIQUE (CORREO) USING INDEX TABLESPACE VIERNES_USUARIOS
) TABLESPACE VIERNES_USUARIOS;

COMMENT ON TABLE CRM_USUARIOS IS 'Usuarios registrados y credenciales de acceso al CRM';