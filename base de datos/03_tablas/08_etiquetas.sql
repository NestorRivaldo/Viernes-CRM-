CREATE TABLE CRM_ETIQUETAS (
    ID_ETIQUETA         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE              VARCHAR2(40 CHAR) NOT NULL,
    NOMBRE_NORMALIZADO  VARCHAR2(80 CHAR) NOT NULL,
    COLOR               VARCHAR2(7 CHAR)  NOT NULL,
    DESCRIPCION         VARCHAR2(160 CHAR),
    ACTIVA              NUMBER(1,0) NOT NULL,
    CREADO_EN           TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_ETIQUETAS PRIMARY KEY (ID_ETIQUETA) USING INDEX TABLESPACE VIERNES_ETIQUETAS,
    CONSTRAINT UK_ETIQUETA_NOMBRE_NORMALIZADO UNIQUE (NOMBRE_NORMALIZADO) USING INDEX TABLESPACE VIERNES_ETIQUETAS
) TABLESPACE VIERNES_ETIQUETAS;