-- =============================================================================
-- TABLAS: CRM_PROPUESTAS y CRM_PROPUESTA_DETALLES
-- Tablespace Datos/Índices: VIERNES_PROPUESTAS, VIERNES_PROP_DET
-- =============================================================================

CREATE TABLE CRM_PROPUESTAS (
    ID                  NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_PROPUESTA    VARCHAR2(50 CHAR) NOT NULL,
    ID_OPORTUNIDAD      NUMBER(19,0) NOT NULL,
    ID_CLIENTE          NUMBER(19,0) NOT NULL,
    CLIENTE_NOMBRE      VARCHAR2(150 CHAR),
    ESTADO              VARCHAR2(20 CHAR) NOT NULL,
    VERSION             NUMBER(10,0) NOT NULL,
    SUBTOTAL            NUMBER(14,2) NOT NULL,
    DESCUENTO           NUMBER(14,2) NOT NULL,
    TOTAL               NUMBER(14,2) NOT NULL,
    RESPONSABLE         VARCHAR2(100 CHAR),
    FECHA_EMISION       DATE NOT NULL,
    FECHA_VENCIMIENTO   DATE,
    OBSERVACIONES       CLOB,
    CREADO_EN           TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_PROPUESTAS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_PROPUESTAS,
    CONSTRAINT UK_CRM_PROPUESTAS_NUMERO UNIQUE (NUMERO_PROPUESTA) USING INDEX TABLESPACE VIERNES_PROPUESTAS
) TABLESPACE VIERNES_PROPUESTAS;

CREATE TABLE CRM_PROPUESTA_DETALLES (
    ID               NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_PROPUESTA     NUMBER(19,0) NOT NULL,
    ID_PRODUCTO      NUMBER(19,0),
    DESCRIPCION      VARCHAR2(500 CHAR) NOT NULL,
    CANTIDAD         NUMBER(10,0) NOT NULL,
    PRECIO_UNITARIO  NUMBER(14,2) NOT NULL,
    SUBTOTAL         NUMBER(14,2) NOT NULL,
    CONSTRAINT PK_CRM_PROPUESTA_DETALLES PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_PROP_DET,
    CONSTRAINT FK_CRM_PROPUESTA_DETALLES_PROPUESTA FOREIGN KEY (ID_PROPUESTA) REFERENCES CRM_PROPUESTAS (ID) ON DELETE CASCADE
) TABLESPACE VIERNES_PROP_DET;

CREATE INDEX IX_CRM_PROPUESTAS_ESTADO ON CRM_PROPUESTAS (ESTADO) TABLESPACE VIERNES_PROPUESTAS;
CREATE INDEX IX_CRM_PROPUESTAS_CLIENTE ON CRM_PROPUESTAS (ID_CLIENTE) TABLESPACE VIERNES_PROPUESTAS;
CREATE INDEX IX_CRM_PROPUESTAS_OPORTUNIDAD ON CRM_PROPUESTAS (ID_OPORTUNIDAD) TABLESPACE VIERNES_PROPUESTAS;
CREATE INDEX IX_CRM_PROPUESTA_DETALLES_PROP ON CRM_PROPUESTA_DETALLES (ID_PROPUESTA) TABLESPACE VIERNES_PROP_DET;