CREATE TABLE CRM_PRODUCTOS (
    ID           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO       VARCHAR2(50 CHAR)  NOT NULL,
    NOMBRE       VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPCION  VARCHAR2(1000 CHAR),
    CATEGORIA    VARCHAR2(100 CHAR),
    PRECIO_BASE  NUMBER(14,2) NOT NULL,
    ESTADO       VARCHAR2(20 CHAR) NOT NULL,
    CREADO_EN    TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_PRODUCTOS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_PRODUCTOS,
    CONSTRAINT UK_CRM_PRODUCTOS_CODIGO UNIQUE (CODIGO) USING INDEX TABLESPACE VIERNES_PRODUCTOS
) TABLESPACE VIERNES_PRODUCTOS;