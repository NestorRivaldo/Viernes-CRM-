-- =============================================================================
-- TABLAS: CRM_FUENTES y CRM_LEADS
-- Tablespace Datos/Índices: VIERNES_FUENTES, VIERNES_LEADS
-- =============================================================================

CREATE TABLE CRM_FUENTES (
    ID           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    CODIGO       VARCHAR2(50 CHAR)  NOT NULL,
    NOMBRE       VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPCION  VARCHAR2(500 CHAR),
    ACTIVA       NUMBER(1,0) NOT NULL,
    CREADO_EN    TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_FUENTES PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_FUENTES,
    CONSTRAINT UK_CRM_FUENTES_CODIGO UNIQUE (CODIGO) USING INDEX TABLESPACE VIERNES_FUENTES
) TABLESPACE VIERNES_FUENTES;

CREATE TABLE CRM_LEADS (
    ID           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(150 CHAR) NOT NULL,
    EMPRESA      VARCHAR2(150 CHAR),
    CORREO       VARCHAR2(150 CHAR),
    TELEFONO     VARCHAR2(30 CHAR),
    FUENTE       VARCHAR2(80 CHAR),
    FUENTE_ID    NUMBER(19,0),
    ESTADO       VARCHAR2(20 CHAR) NOT NULL,
    RESPONSABLE  VARCHAR2(100 CHAR),
    FECHA        DATE,
    CREADO_EN    TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_LEADS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_LEADS
) TABLESPACE VIERNES_LEADS;

CREATE INDEX IX_CRM_LEADS_ESTADO ON CRM_LEADS (ESTADO) TABLESPACE VIERNES_LEADS;
CREATE INDEX IX_CRM_LEADS_FUENTE ON CRM_LEADS (FUENTE_ID) TABLESPACE VIERNES_LEADS;