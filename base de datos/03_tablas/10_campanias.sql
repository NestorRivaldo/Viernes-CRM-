-- =============================================================================
-- TABLAS: CRM_CAMPANIAS y CRM_CAMPANIA_LEADS
-- Tablespace Datos/Índices: VIERNES_CAMPANIAS, VIERNES_CAMP_LEADS
-- =============================================================================

CREATE TABLE CRM_CAMPANIAS (
    ID            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE        VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPCION   VARCHAR2(1000 CHAR),
    FECHA_INICIO  DATE,
    FECHA_FIN     DATE,
    ESTADO        VARCHAR2(20 CHAR) NOT NULL,
    CREADO_EN     TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_CAMPANIAS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_CAMPANIAS
) TABLESPACE VIERNES_CAMPANIAS;

CREATE TABLE CRM_CAMPANIA_LEADS (
    ID            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    CAMPANIA_ID   NUMBER(19,0) NOT NULL,
    LEAD_ID       NUMBER(19,0) NOT NULL,
    CREADO_EN     TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_CAMPANIA_LEADS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_CAMP_LEADS,
    CONSTRAINT UK_CAMPANIA_LEAD UNIQUE (CAMPANIA_ID, LEAD_ID) USING INDEX TABLESPACE VIERNES_CAMP_LEADS
) TABLESPACE VIERNES_CAMP_LEADS;

CREATE INDEX IX_CRM_CAMPANIA_LEADS_LEAD ON CRM_CAMPANIA_LEADS (LEAD_ID) TABLESPACE VIERNES_CAMP_LEADS;