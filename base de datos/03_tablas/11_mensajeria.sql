CREATE TABLE CRM_MENSAJES (
    ID              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_CORREO  VARCHAR2(150 CHAR) NOT NULL,
    USUARIO_NOMBRE  VARCHAR2(200 CHAR) NOT NULL,
    CONTENIDO       VARCHAR2(2000 CHAR) NOT NULL,
    CREADO_EN       TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_MENSAJES PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_MENSAJES
) TABLESPACE VIERNES_MENSAJES;

CREATE INDEX IX_CRM_MENSAJES_CREADO ON CRM_MENSAJES (CREADO_EN) TABLESPACE VIERNES_MENSAJES;