-- =============================================================================
-- TABLAS: CRM_CLIENTES y CRM_CONTACTOS
-- Tablespace Datos/Índices: VIERNES_CLIENTES, VIERNES_CONTACTOS
-- =============================================================================

CREATE TABLE CRM_CLIENTES (
    ID                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE            VARCHAR2(150 CHAR) NOT NULL,
    EMPRESA           VARCHAR2(150 CHAR),
    TIPO_DOCUMENTO    VARCHAR2(10 CHAR),
    NUMERO_DOCUMENTO  VARCHAR2(20 CHAR),
    CORREO            VARCHAR2(150 CHAR),
    TELEFONO          VARCHAR2(30 CHAR),
    ESTADO            VARCHAR2(20 CHAR) NOT NULL,
    RESPONSABLE       VARCHAR2(100 CHAR),
    CREADO_EN         TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_CLIENTES PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_CLIENTES,
    CONSTRAINT UK_CRM_CLIENTES_DOCUMENTO UNIQUE (TIPO_DOCUMENTO, NUMERO_DOCUMENTO) USING INDEX TABLESPACE VIERNES_CLIENTES
) TABLESPACE VIERNES_CLIENTES;

CREATE TABLE CRM_CONTACTOS (
    ID          NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_CLIENTE  NUMBER(19,0) NOT NULL,
    NOMBRE      VARCHAR2(100 CHAR) NOT NULL,
    APELLIDO    VARCHAR2(100 CHAR),
    CARGO       VARCHAR2(100 CHAR),
    CORREO      VARCHAR2(150 CHAR),
    TELEFONO    VARCHAR2(30 CHAR),
    PRINCIPAL   NUMBER(1,0),
    CREADO_EN   TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_CONTACTOS PRIMARY KEY (ID) USING INDEX TABLESPACE VIERNES_CONTACTOS,
    CONSTRAINT FK_CRM_CONTACTOS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CRM_CLIENTES (ID) ON DELETE CASCADE
) TABLESPACE VIERNES_CONTACTOS;

CREATE INDEX IX_CRM_CONTACTOS_CLIENTE ON CRM_CONTACTOS (ID_CLIENTE) TABLESPACE VIERNES_CONTACTOS;