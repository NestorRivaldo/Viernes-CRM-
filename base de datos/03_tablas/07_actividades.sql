-- TABLAS: CRM_ACTIVIDADES y PARTICIPANTES/ETIQUETAS
-- Tablespace Datos/Índices: VIERNES_ACTIVIDADES, VIERNES_ACT_ETIQ, VIERNES_ACT_PART
-- =============================================================================

CREATE TABLE CRM_ACTIVIDADES (
    ID_ACTIVIDAD    NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO      VARCHAR2(255 CHAR),
    ID_CLIENTE      NUMBER(19,0),
    ID_LEAD         NUMBER(19,0),
    ID_OPORTUNIDAD  NUMBER(19,0),
    TIPO            VARCHAR2(255 CHAR) NOT NULL,
    TITULO          VARCHAR2(255 CHAR) NOT NULL,
    DESCRIPCION     CLOB,
    FECHA           TIMESTAMP(6) NOT NULL,
    ESTADO          VARCHAR2(255 CHAR) NOT NULL,
    CREADO_EN       TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_ACTIVIDADES PRIMARY KEY (ID_ACTIVIDAD) USING INDEX TABLESPACE VIERNES_ACTIVIDADES
) TABLESPACE VIERNES_ACTIVIDADES;

CREATE TABLE CRM_ACTIVIDAD_ETIQUETAS (
    ID_ACTIVIDAD_ETIQUETA  NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_ACTIVIDAD           NUMBER(19,0) NOT NULL,
    ID_ETIQUETA            NUMBER(19,0) NOT NULL,
    CREADO_EN              TIMESTAMP(6) NOT NULL,
    ORDEN                  NUMBER(10,0),
    CONSTRAINT PK_CRM_ACTIVIDAD_ETIQUETAS PRIMARY KEY (ID_ACTIVIDAD_ETIQUETA) USING INDEX TABLESPACE VIERNES_ACT_ETIQ,
    CONSTRAINT UK_ACTIVIDAD_ETIQUETA UNIQUE (ID_ACTIVIDAD, ID_ETIQUETA) USING INDEX TABLESPACE VIERNES_ACT_ETIQ
) TABLESPACE VIERNES_ACT_ETIQ;

CREATE TABLE CRM_ACTIVIDAD_PARTICIPANTES (
    ID_PARTICIPANTE  NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    ID_ACTIVIDAD     NUMBER(19,0) NOT NULL,
    ID_CONTACTO      NUMBER(19,0) NOT NULL,
    CREADO_EN        TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CRM_ACTIVIDAD_PARTICIPANTES PRIMARY KEY (ID_PARTICIPANTE) USING INDEX TABLESPACE VIERNES_ACT_PART,
    CONSTRAINT UK_ACTIVIDAD_CONTACTO UNIQUE (ID_ACTIVIDAD, ID_CONTACTO) USING INDEX TABLESPACE VIERNES_ACT_PART
) TABLESPACE VIERNES_ACT_PART;

CREATE INDEX IX_CRM_ACTIVIDADES_ESTADO ON CRM_ACTIVIDADES (ESTADO) TABLESPACE VIERNES_ACTIVIDADES;
CREATE INDEX IX_CRM_ACTIVIDADES_FECHA ON CRM_ACTIVIDADES (FECHA) TABLESPACE VIERNES_ACTIVIDADES;
CREATE INDEX IX_CRM_ACTIVIDADES_CLIENTE ON CRM_ACTIVIDADES (ID_CLIENTE) TABLESPACE VIERNES_ACTIVIDADES;
CREATE INDEX IX_CRM_ACTIVIDADES_OPORTUNIDAD ON CRM_ACTIVIDADES (ID_OPORTUNIDAD) TABLESPACE VIERNES_ACTIVIDADES;
CREATE INDEX IX_CRM_ACTIVIDAD_ETIQUETAS_ET ON CRM_ACTIVIDAD_ETIQUETAS (ID_ETIQUETA) TABLESPACE VIERNES_ACT_ETIQ;
CREATE INDEX IX_CRM_ACTIVIDAD_PARTICIPANTES_CT ON CRM_ACTIVIDAD_PARTICIPANTES (ID_CONTACTO) TABLESPACE VIERNES_ACT_PART;