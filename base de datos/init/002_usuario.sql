ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_OPOR_PROD;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_PROPUESTAS;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_PROP_DET;
