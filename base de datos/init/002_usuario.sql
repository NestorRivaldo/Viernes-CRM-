GRANT CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER,
      CREATE TYPE, CREATE SYNONYM, CREATE MATERIALIZED VIEW, CREATE JOB
   TO BOM_VENTAS;

GRANT SELECT ON SYS.DBA_TABLESPACES TO BOM_VENTAS;
GRANT SELECT ON SYS.DBA_DATA_FILES TO BOM_VENTAS;
GRANT SELECT ON SYS.DBA_TEMP_FILES TO BOM_VENTAS;
GRANT SELECT ON SYS.DBA_FREE_SPACE TO BOM_VENTAS;

CREATE OR REPLACE DIRECTORY VIERNES_BACKUP AS '/opt/oracle/backup';
GRANT READ, WRITE ON DIRECTORY VIERNES_BACKUP TO BOM_VENTAS;

PROMPT [OK] Usuario BOM_VENTAS configurado con cuotas y permisos.