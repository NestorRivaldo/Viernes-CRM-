ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_USUARIOS;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_CLIENTES;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_CONTACTOS;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_FUENTES;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_LEADS;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_PRODUCTOS;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_OPORTUNIDADES;
ALTER USER BOM_VENTAS QUOTA UNLIMITED ON VIERNES_OPOR_CONTACTOS;
