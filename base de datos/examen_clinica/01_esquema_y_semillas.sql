-- 3. Crear Tablas
CREATE TABLE EXA_CLINICA.CLINICAS (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUC           CHAR(11)      NOT NULL,
    RAZON_SOCIAL  VARCHAR2(150) NOT NULL,
    TELEFONO      VARCHAR2(20),
    ACTIVO        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_CLINICA_RUC UNIQUE (RUC),
    CONSTRAINT CK_CLINICA_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE EXA_CLINICA.CONSULTORIOS (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA    NUMBER        NOT NULL,
    CODIGO        VARCHAR2(10)  NOT NULL,
    TARIFA_HORA   NUMBER(8,2)   NOT NULL,
    ESTADO        VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT FK_CONSULTORIO_CLINICA FOREIGN KEY (ID_CLINICA)
        REFERENCES EXA_CLINICA.CLINICAS(ID),
    CONSTRAINT UQ_CONSULTORIO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_CONSULTORIO_TARIFA CHECK (TARIFA_HORA > 0),
    CONSTRAINT CK_CONSULTORIO_ESTADO CHECK (ESTADO IN ('DISPONIBLE', 'OCUPADO', 'MANTENIMIENTO'))
);

CREATE TABLE EXA_CLINICA.ESPECIALIDADES (
    ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO  VARCHAR2(10)  NOT NULL,
    NOMBRE  VARCHAR2(100) NOT NULL,
    CONSTRAINT UQ_ESPECIALIDAD_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE EXA_CLINICA.CONSULTORIO_ESPECIALIDAD (
    ID_CONSULTORIO  NUMBER NOT NULL,
    ID_ESPECIALIDAD NUMBER NOT NULL,
    CONSTRAINT PK_CONSULTORIO_ESPECIALIDAD PRIMARY KEY (ID_CONSULTORIO, ID_ESPECIALIDAD),
    CONSTRAINT FK_CE_CONSULTORIO FOREIGN KEY (ID_CONSULTORIO) REFERENCES EXA_CLINICA.CONSULTORIOS(ID),
    CONSTRAINT FK_CE_ESPECIALIDAD FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES EXA_CLINICA.ESPECIALIDADES(ID)
);

CREATE INDEX EXA_CLINICA.IDX_CONSULTORIO_CLINICA ON EXA_CLINICA.CONSULTORIOS(ID_CLINICA);

